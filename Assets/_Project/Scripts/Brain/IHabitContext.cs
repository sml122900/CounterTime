namespace CounterTime.Brain
{
    /// <summary>
    /// 습관 조건이 평가되는 대상 — 브레인 주인 한 명의 시점이다. '내'가 곧 그 선수다.
    ///
    /// <b>습관 조건 전용이다. 폴백 가중치는 이 면을 쓰지 않는다.</b>
    /// §4 사다리 3단(그립·체력·지도수·시계 가중 무작위)은 별도 인터페이스를 3단계에서
    /// 정의한다. 지도 <i>개수</i>와 시계는 그쪽에만 들어간다 — 여기로 들어오면 습관이
    /// 상태 평가형 AI 로 흐르고, 그건 §2 에서 배제된 안이다.
    ///
    /// <b>멤버 추가는 새 습관이 실제로 요구할 때만.</b> 지금 넷은 각각 H1/H2/H3 이
    /// 요구해서 있다. "나중에 쓸 것 같아서" 는 사유가 아니다.
    /// </summary>
    public interface IHabitContext
    {
        /// H1 — §3 유효 잡기, −2 … +2. Core 의 <c>GripSystem.EffectiveGrip</c> 값 그대로.
        int OwnEffectiveGrip { get; }

        /// <summary>
        /// H2 — 내가 지도를 받은 뒤 교환이 몇 번 지났는가. <c>null</c> = 아직 받은 적 없음.
        ///
        /// <b>턴의 정의(여기서 못 박는다):</b>
        /// <list type="bullet">
        /// <item>1턴 = 엔진이 해결한 <b>교환 1회</b>. 교환을 소비하지 않는 노드
        /// (자세만 선언·서술·결과)는 세지 않는다 — 러너가 이미 그런 노드를 시계에서
        /// 빼고 있고(§2), 여기서만 다르게 세면 "2턴 내"가 배선 위치에 따라 달라진다.</item>
        /// <item>지도가 난 교환 <b>직후</b>가 0 이다. 그 교환 자체는 세지 않는다 —
        /// B 의 커밋은 그 교환이 해결되기 전에 이미 정해졌으므로 반응할 수 없다.</item>
        /// <item>따라서 H2 의 "2턴 내" 는 <c>0</c> 과 <c>1</c>, <b>정확히 두 번</b>의
        /// 커밋이다. <c>&lt;= 2</c> 는 세 번이 되어 틀린다.</item>
        /// </list>
        /// </summary>
        int? TurnsSinceOwnShido { get; }

        /// H3 — 내 체력.
        int OwnStamina { get; }

        /// H3 — 상대 체력. 열세 판정에만 쓴다.
        int OpponentStamina { get; }

        /// §H 3.5b — 8강 서도현 H1("내가 큰 기술을 예고하면 카운터 준비"). "예고"는
        /// 독심이 아니라 §4.4 흔들기(Setup)다 — 흔들기는 큰기술보다 한 교환 먼저
        /// 해결되는 실제 게임 상태라, 그 다음 교환 시점엔 이미 지나간 사실이다(인과
        /// 순서를 안 어긴다). <c>MatchEngine.IsSetupActive</c> 를 상대(=나를 상대하는
        /// 선수) 기준으로 그대로 읽는다.
        bool OpponentSetupActive { get; }

        /// §H 3.5b — 8강 서도현 H2("밸런스 온전 시 방어")와 4강 임준철의 변칙기(안오금띄기,
        /// "내 밸런스가 낮을 때") 둘 다 요구한다. <c>MatchEngine.Balance.Get</c> 을
        /// 그대로 읽는다 — 파생 없음.
        int OwnBalance { get; }
    }
}
